int OV5640_ShowFrame(void)
{
    /* 摄像头DMA直接写DDR，显示前使CPU缓存失效以读取新数据。 */
    Xil_DCacheInvalidateRange((UINTPTR)ov5640_buff,
            OV5640_STRIDE_BYTES * OV5640_FRAME_HEIGHT);
    LCD_ShowPicture(ov5640_buff, OV5640_LCD_X_OFFSET, OV5640_LCD_Y_OFFSET,
            OV5640_FRAME_WIDTH, OV5640_FRAME_HEIGHT, OV5640_LCD_SCALE);
    LCD_Refresh();
    return XST_SUCCESS;
}

const uint8_t *OV5640_GetRawFrame(void)
{
    /* 返回 DDR 中的原始 24 位帧；低地址到高地址为 B、G、R。 */
    Xil_DCacheInvalidateRange((UINTPTR)ov5640_buff,
            OV5640_STRIDE_BYTES * OV5640_FRAME_HEIGHT);
    return ov5640_buff;
}

void OV5640_GetInferenceFrame(short *image)
{
    unsigned int row;
    unsigned int col;
    unsigned int pixels = OV5640_FRAME_WIDTH * OV5640_FRAME_HEIGHT;

    if (image == NULL) {
        return;
    }

    /* 搬运前使源缓存失效；该操作不暂停采集，也不保证单缓冲帧冻结。 */
    Xil_DCacheInvalidateRange((UINTPTR)ov5640_buff,
            OV5640_STRIDE_BYTES * OV5640_FRAME_HEIGHT);
    for (row = 0U; row < OV5640_FRAME_HEIGHT; ++row) {
        for (col = 0U; col < OV5640_FRAME_WIDTH; ++col) {
            const uint8_t *pixel = ov5640_buff +
                    (row * OV5640_FRAME_WIDTH + col) * OV5640_BYTES_PER_PIXEL;
            unsigned int index = row * OV5640_FRAME_WIDTH + col;
            /* DDR依次存放B、G、R；填入RGB平面，并将0至255线性映射到0至1024。 */
            image[index] = (short)(((int)pixel[2] * 2048 - 255 * 1024) / 255 );
            /* 模块偏绿：只对推理输入的 G 通道做固定衰减，R/B 不变。 */
            {
                int green = ((int)pixel[1] * OV5640_G_GAIN_NUM) /
                        OV5640_G_GAIN_DEN;
                image[pixels + index] =
                        (short)((green * 2048 - 255 * 1024) / 255 );
            }
            image[2U * pixels + index] = (short)(((int)pixel[0] * 2048 - 255 * 1024) / 255 );
        }
    }

#if OV5640_DEBUG_DUMP
    SD_Transfer_write("Test//Out.bin",(u32)ov5640_buff,(u32)224*224*3);
    /* 调试：同时保存模型真正使用的 RGB Q10 三平面，方便和 Out.bin(BGR) 对照。 */
    SD_Transfer_write("Test//Infer.bin", (u32)image,
            (u32)(pixels * 3U * sizeof(short)));
#endif

    Xil_DCacheFlushRange((INTPTR)image,
            pixels * 3U * sizeof(short));
}
