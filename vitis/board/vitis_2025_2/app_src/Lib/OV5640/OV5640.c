int OV5640_Init(void){
    int Status;
    u8 ChipIdHigh;
    u8 ChipIdLow;

    
    if (IicPs1.IsReady != XIL_COMPONENT_IS_READY) {
        Status = IIC_Init(&IicPs1, HW_IIC1_BASEADDR,
                OV5640_IIC_SCLK_HZ);
        if (Status != XST_SUCCESS) {
            UART_Print("OV5640 IIC init failed: %d\r\n", Status);
            return Status;
        }
    } else {
        XIicPs_Abort(&IicPs1);
        Status = XIicPs_SetSClk(&IicPs1, OV5640_IIC_SCLK_HZ);
        if (Status != XST_SUCCESS) {
            UART_Print("OV5640 I2C1 clock setup failed: %d\r\n", Status);
            return Status;
        }
        Status = XIicPs_SetOptions(&IicPs1, XIICPS_7_BIT_ADDR_OPTION);
        if (Status != XST_SUCCESS) {
            UART_Print("OV5640 I2C1 address setup failed: %d\r\n", Status);
            return Status;
        }
    }

    
    Status = OV5640_RecoverIic();
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 I2C1 bus busy before first register write: %d\r\n",
                Status);
        return Status;
    }

    
    Status = OV5640_WriteReg(0x3008, 0x82);
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 software reset write failed: %d\r\n", Status);
        return Status;
    }
    usleep(OV5640_RESET_DELAY_US);

    Status = OV5640_WriteReg(0x3008, 0x42);
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 standby write failed: %d\r\n", Status);
        return Status;
    }

    /* 读取芯片标识，确认IIC通信和器件型号。 */
    Status = OV5640_ReadReg(0x300A, &ChipIdHigh);
    if (Status == XST_SUCCESS) {
        Status = OV5640_ReadReg(0x300B, &ChipIdLow);
    }
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 chip ID read failed: %d\r\n", Status);
        return Status;
    }
    if ((ChipIdHigh != 0x56U) || (ChipIdLow != 0x40U)) {
        UART_Print("OV5640 unexpected chip ID: 0x%x 0x%x\r\n",
                ChipIdHigh, ChipIdLow);
        return XST_FAILURE;
    }
    UART_Print("OV5640 chip ID OK: 0x%x 0x%x\r\n", ChipIdHigh, ChipIdLow);

//    OV5640_WriteReg(0x3406, 0x01);
//
//    OV5640_WriteReg(0x3400, 0x06);  /* R 高字节 */
//    OV5640_WriteReg(0x3401, 0xCC);  /* R 低字节 */
//    OV5640_WriteReg(0x3402, 0x04);  /* G 高字节 */
//    OV5640_WriteReg(0x3403, 0x3F);
//    OV5640_WriteReg(0x3404, 0x03);  /* B 高字节 */
//    OV5640_WriteReg(0x3405, 0x66);

    for (unsigned int i = 0; i < sizeof(Reg_Init) / sizeof(Reg_Init[0]) / 2U;
            ++i) {
        Status = OV5640_WriteReg(Reg_Init[i * 2], Reg_Init[i * 2 + 1]);
        if (Status != XST_SUCCESS) {
            UART_Print("OV5640 register 0x%x=0x%x write failed: %d\r\n",
                    Reg_Init[i * 2], Reg_Init[i * 2 + 1], Status);
            return Status;
        }
    }

    
    Status = OV5640_WriteReg(0x3008, 0x02);
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 final wake write failed: %d\r\n", Status);
        return Status;
    }
    usleep(OV5640_RESET_DELAY_US);

    Status = run_triple_frame_buffer_ov5640(&LCD_Ptr, 0, OV5640_FRAME_WIDTH,
            OV5640_FRAME_HEIGHT, (int)ov5640_src_addr, 0, 0);
    if (Status != XST_SUCCESS) {
        UART_Print("OV5640 VDMA setup failed: %d\r\n", Status);
    } else {
        UART_Print("OV5640 VDMA configured: buffer=0x%x, %dx%d, stride=%d\r\n",
                (unsigned int)ov5640_src_addr, OV5640_FRAME_WIDTH,
                OV5640_FRAME_HEIGHT, OV5640_STRIDE_BYTES);
    }
#if OV5640_AF_ENABLE
    if (Status == XST_SUCCESS) {
        Status = OV5640_AF_Init();
        if (Status == XST_SUCCESS) {
#if OV5640_AF_STARTUP_TRIGGER
            Status = OV5640_AF_Trigger();
#endif
        }
        if (Status != XST_SUCCESS) {
            UART_Print("OV5640 AF initialization failed: %d\r\n", Status);
        }
    }
#endif
    return Status;
}

static int OV5640_AF_WriteBlock(u16 RegAddr, const u8 *Data, u32 Length)
{
    unsigned int Retry;
    int Status = XST_FAILURE;

    if ((Data == NULL) || (Length == 0U)) {
        return XST_INVALID_PARAM;
    }

    for (Retry = 0U; Retry < OV5640_IIC_RETRY_COUNT; ++Retry) {
        Status = OV5640_RecoverIic();
        if (Status != XST_SUCCESS) {
            return Status;
        }

        Status = PS_IIC_SeqWrite_Reg(&IicPs1, OV5640_ADDR, REG16,
                RegAddr, (u8 *)Data, Length);
        if (Status == XST_SUCCESS) {
            return XST_SUCCESS;
        }
        if ((Status != XST_IIC_BUS_BUSY) &&
                (Status != XST_IIC_ARB_LOST)) {
            return Status;
        }
        (void)OV5640_ResetIicController();
    }

    return Status;
}

static int OV5640_AF_WaitStatus(u8 ExpectedStatus)
{
    unsigned int ElapsedUs = 0U;
    u8 Status;
    int Result;

    while (ElapsedUs < OV5640_AF_STATUS_TIMEOUT_US) {
        Result = OV5640_ReadReg(OV5640_AF_CMD_STATUS, &Status);
        if (Result != XST_SUCCESS) {
            return Result;
        }
        if (Status == ExpectedStatus) {
            return XST_SUCCESS;
        }
        usleep(OV5640_AF_STATUS_POLL_US);
        ElapsedUs += OV5640_AF_STATUS_POLL_US;
    }

    UART_Print("OV5640 AF status timeout: expected 0x%x\r\n",
            ExpectedStatus);
    return XST_FAILURE;
}

/* 等待自动对焦命令应答寄存器清零。 */
static int OV5640_AF_WaitAckClear(void)
{
    unsigned int ElapsedUs = 0U;
    u8 Ack;
    int Result;

    while (ElapsedUs < OV5640_AF_STATUS_TIMEOUT_US) {
        Result = OV5640_ReadReg(OV5640_AF_CMD_ACK, &Ack);
        if (Result != XST_SUCCESS) {
            return Result;
        }
        if (Ack == 0x00U) {
            return XST_SUCCESS;
        }
        usleep(OV5640_AF_STATUS_POLL_US);
        ElapsedUs += OV5640_AF_STATUS_POLL_US;
    }
    UART_Print("OV5640 AF command acknowledgement timeout\r\n");
    return XST_FAILURE;
}

int OV5640_AF_Init(void)
{
    static int Initialized = 0;
    u32 Offset;
    u32 Length;
    u8 Status;
    int Result;

    /* 防止主程序重复调用时再次下载固件并复位自动对焦控制器。 */
    if (Initialized != 0) {
        return XST_SUCCESS;
    }

    Result = OV5640_WriteReg(OV5640_AF_MCU_RESET, 0x20U);
    if (Result != XST_SUCCESS) {
        return Result;
    }

    for (Offset = 0U; Offset < sizeof(OV5640_AF_Firmware); ) {
        Length = sizeof(OV5640_AF_Firmware) - Offset;
        if (Length > OV5640_AF_CHUNK_BYTES) {
            Length = OV5640_AF_CHUNK_BYTES;
        }
        Result = OV5640_AF_WriteBlock(
                (u16)(OV5640_AF_DOWNLOAD_ADDR + Offset),
                &OV5640_AF_Firmware[Offset], Length);
        if (Result != XST_SUCCESS) {
            UART_Print("OV5640 AF firmware write failed at 0x%x: %d\r\n",
                    (unsigned int)(OV5640_AF_DOWNLOAD_ADDR + Offset), Result);
            return Result;
        }
        Offset += Length;
    }

    Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x00U);
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_CMD_ACK, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(0x3024U, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(0x3025U, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(0x3026U, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(0x3027U, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(0x3028U, 0x00U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_CMD_STATUS, 0x7fU);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_MCU_RESET, 0x00U);
    }
    if (Result != XST_SUCCESS) {
        UART_Print("OV5640 AF controller start failed: %d\r\n", Result);
        return Result;
    }

    Result = OV5640_AF_WaitStatus(OV5640_AF_STATUS_IDLE);
    if (Result == XST_SUCCESS) {
        u8 Value;

        /* 打开自动对焦控制器的时钟，并解除控制器复位。 */
        Result = OV5640_ReadReg(OV5640_AF_MCU_CLOCK, &Value);
        if (Result == XST_SUCCESS) {
            Result = OV5640_WriteReg(OV5640_AF_MCU_CLOCK,
                    (u8)(Value | 0x60U));
        }
        if (Result == XST_SUCCESS) {
            Result = OV5640_ReadReg(OV5640_AF_AFC_RESET, &Value);
        }
        if (Result == XST_SUCCESS) {
            Result = OV5640_WriteReg(OV5640_AF_AFC_RESET,
                    (u8)(Value & (u8)~0x40U));
        }
        if (Result == XST_SUCCESS) {
            Result = OV5640_ReadReg(OV5640_AF_AFC_CLOCK, &Value);
        }
        if (Result == XST_SUCCESS) {
            Result = OV5640_WriteReg(OV5640_AF_AFC_CLOCK,
                    (u8)(Value | 0x40U));
        }
        if (Result == XST_SUCCESS) {
            /* 使能OV5640内部VCM镜头驱动，避免固件空跑但马达不动作。 */
            Result = OV5640_WriteReg(OV5640_AF_VCM_CONTROL, 0x3fU);
        }
    }
    if (Result == XST_SUCCESS) {
        (void)OV5640_ReadReg(OV5640_AF_CMD_STATUS, &Status);
        UART_Print("OV5640 AF firmware ready: status=0x%x, bytes=%d\r\n",
                Status, (unsigned int)sizeof(OV5640_AF_Firmware));
        Initialized = 1;
    }
    return Result;
}

int OV5640_AF_Trigger(void)
{
    int Result;

    /* 先结束上一次命令，再提交单次对焦命令。 */
    Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x01U);
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x08U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_AF_WaitAckClear();
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_CMD_ACK, 0x01U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x03U);
    }
    if (Result == XST_SUCCESS) {
        Result = OV5640_AF_WaitAckClear();
    }
    if (Result != XST_SUCCESS) {
        return Result;
    }

    Result = OV5640_AF_WaitStatus(OV5640_AF_STATUS_FOCUSED);
    if (Result != XST_SUCCESS) {
        return Result;
    }

    /* 对焦完成后暂停，保持当前镜头位置。 */
    Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x06U);
    if (Result == XST_SUCCESS) {
        UART_Print("OV5640 AF focused\r\n");
    }
    return Result;
}

int OV5640_AF_Release(void)
{
    int Result = OV5640_WriteReg(OV5640_AF_CMD_MAIN, 0x08U);

    if (Result == XST_SUCCESS) {
        Result = OV5640_AF_WaitStatus(OV5640_AF_STATUS_IDLE);
    }
    return Result;
}

int OV5640_AF_GetStatus(u8 *Status)
{
    if (Status == NULL) {
        return XST_INVALID_PARAM;
    }
    return OV5640_ReadReg(OV5640_AF_CMD_STATUS, Status);
}

static int OV5640_WriteReg(u16 RegAddr, u8 RegValue)
{
    unsigned int Retry;
    int Status;

    for (Retry = 0U; Retry < OV5640_IIC_RETRY_COUNT; ++Retry) {
        Status = OV5640_RecoverIic();
        if (Status != XST_SUCCESS) {
            return Status;
        }

        Status = PS_IIC_SeqWrite_Reg(&IicPs1, OV5640_ADDR, REG16,
                RegAddr, &RegValue, 1U);
        if (Status == XST_SUCCESS) {
            return XST_SUCCESS;
        }
        if ((Status != XST_IIC_BUS_BUSY) &&
                (Status != XST_IIC_ARB_LOST)) {
            return Status;
        }

        (void)OV5640_ResetIicController();
    }

    return Status;
}

