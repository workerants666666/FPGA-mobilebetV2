#ifndef TRASH_HW_CONFIG_H
#define TRASH_HW_CONFIG_H

#include "xparameters.h"
#include "xil_types.h"

/* Use physical peripheral labels: the sole enabled UART1 is canonical
 * XUARTPS_0 in SDT; that index is not the PS UART number. */
#define HW_UART1_BASEADDR ((UINTPTR)XPAR_UART1_BASEADDR)
#define HW_IIC0_BASEADDR ((UINTPTR)XPAR_I2C0_BASEADDR)
#define HW_IIC1_BASEADDR ((UINTPTR)XPAR_I2C1_BASEADDR)
#define HW_GIC_BASEADDR ((UINTPTR)XPAR_XSCUGIC_0_BASEADDR)
#define HW_GPIO_BASEADDR ((UINTPTR)XPAR_XGPIOPS_0_BASEADDR)
#define HW_VDMA_BASEADDR ((UINTPTR)XPAR_AXI_VDMA_0_BASEADDR)
#define HW_VTC_BASEADDR ((UINTPTR)XPAR_V_TC_0_BASEADDR)
#define HW_DDR_BASEADDR ((UINTPTR)XPAR_PS7_DDR_0_BASEADDRESS)
#define HW_SCUTIMER_BASEADDR ((UINTPTR)XPAR_XSCUTIMER_0_BASEADDR)

/* These peripherals use GIC SPI interrupts. SDT stores trigger flags above
 * bit 11 and numbers SPIs from zero; XScuGic_Connect takes the GIC ID. */
#define HW_SPI_INTR_ID(encoded) (((encoded) & 0xFFFU) + 32U)
#define HW_UART1_INTR_ID HW_SPI_INTR_ID(XPAR_UART1_INTERRUPTS)
#define HW_IIC0_INTR_ID HW_SPI_INTR_ID(XPAR_XIICPS_0_INTERRUPTS)
#define HW_IIC1_INTR_ID HW_SPI_INTR_ID(XPAR_XIICPS_1_INTERRUPTS)
#define HW_GPIO_INTR_ID HW_SPI_INTR_ID(XPAR_XGPIOPS_0_INTERRUPTS)

/* The HLS register drivers belong to this application; no legacy DeviceId
 * tables or copies of the old xparameters.h are used. */
#define TRASH_CONV_BASEADDR ((UINTPTR)XPAR_CONV_0_BASEADDR)
#define TRASH_FC_BASEADDR ((UINTPTR)XPAR_FC_0_BASEADDR)
#define TRASH_PWDWCONV_BASEADDR ((UINTPTR)XPAR_PWDWCONV_0_BASEADDR)
#define TRASH_SHORTCUT_BASEADDR ((UINTPTR)XPAR_SHORTCUT_0_BASEADDR)

#define HW_LCD_BUFFER_ADDR (HW_DDR_BASEADDR + 0x12000000U)
#define HW_CAMERA_BUFFER_ADDR (HW_DDR_BASEADDR + 0x12300000U)
#define HW_SAMPLE_BUFFER_ADDR (HW_DDR_BASEADDR + 0x12400000U)

#endif
